"""Generate searchable and visual icon references from the live asset library."""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import sys

from asset_library import inspect_library, write_if_changed

ROOT = Path(__file__).resolve().parents[1]


def catalogue_files(root=ROOT):
    root = root.resolve()
    sources, _, _, _ = inspect_library(root)
    index = root / 'assets/index.json'
    metadata = {record['name']: record for record in json.loads(index.read_text(encoding='utf-8'))} if index.exists() else {}
    groups = defaultdict(list)
    for name, source in sources.items():
        relative = source.relative_to(root / 'assets')
        category = relative.parts[0] if len(relative.parts) > 1 else 'other'
        record = dict(metadata.get(name, {}))
        record.update(name=name, path=relative.as_posix())
        record.setdefault('description', name.replace('-', ' ').replace('_', ' ').capitalize())
        groups[category].append(record)

    markdown = [
        '# Illustration catalogue', '',
        '<!-- Generated by scripts/build-asset-catalogue.py; do not edit by hand. -->', '',
        f'The library contains **{len(sources)} illustrations**. Every entry includes a copyable command.',
        'Original source artwork and export names are preserved for provenance.', '',
        'Start with the [icon guide](../docs/ICONS.md) or the printable cheat sheet.',
        'Use `\\asset[width=2cm]{name}` for any icon. Letter-only names may also',
        'have a shortcut when it does not conflict with an existing command.', '',
        'Build the visual catalogue with `python3 scripts/build.py examples/asset-catalogue.tex`.', '',
    ]
    duplicates = [r for entries in groups.values() for r in entries if 'visual_duplicate_of' in r]
    if duplicates:
        markdown += ['## Visual duplicates', '', 'Separate original exports are retained.', '']
        for record in sorted(duplicates, key=lambda r: r['name']):
            markdown.append(f"- `{record['name']}` renders like `{record['visual_duplicate_of']}`.")

    tex = [
        '% Generated by scripts/build-asset-catalogue.py; edit artwork/metadata instead.',
        r'\documentclass[aspectratio=169]{beamer}', r'\usetheme{bitpolito}', r'\usepackage{courier}',
        r'\begin{document}',
    ]
    for category, entries in sorted(groups.items()):
        entries.sort(key=lambda record: record['name'])
        title = category.replace('-', ' ').replace('_', ' ').title()
        markdown += ['', '## ' + title, '',
                     '| Icon | Command | Description | Original export |',
                     '| --- | --- | --- | --- |']
        for record in entries:
            name = record['name']
            description = record['description'].rstrip('.') + '.'
            if record.get('identification') == 'uncertain':
                description += ' **Meaning uncertain.**'
            description = description.replace('|', r'\|')
            original = '`' + record['original'] + '`' if record.get('original') else 'Not recorded'
            markdown.append(f"| [{name}]({record['path']}) | `\\asset{{{name}}}` | {description} | {original} |")
        for offset in range(0, len(entries), 9):
            tex += [r'\begin{frame}{' + title + f' / {offset // 9 + 1}' + '}',
                    r'\centering', r'\setlength{\tabcolsep}{0pt}',
                    r'\begin{tabular}{@{}p{0.33\textwidth}p{0.33\textwidth}p{0.33\textwidth}@{}}']
            cells = []
            for record in entries[offset:offset + 9]:
                name = record['name']
                cells.append(
                    r'\centering\colorbox{bitpolito-light}{\parbox[c][0.95cm][c]{0.85\linewidth}{\centering'
                    + r'\asset[width=\linewidth,height=0.80cm]{' + name + '}}}'
                    + r'\par\vspace{0.12cm}{\fontsize{7}{8}\selectfont\ttfamily\detokenize{\asset{' + name + '}}}'
                )
            while len(cells) % 3:
                cells.append('')
            for start in range(0, len(cells), 3):
                tex.append(' & '.join(cells[start:start + 3]) + r'\tabularnewline[0.24cm]')
            tex += [r'\end{tabular}', r'\end{frame}']
    tex.append(r'\end{document}')
    return {
        'assets/CATALOGUE.md': ('\n'.join(markdown) + '\n').encode('utf-8'),
        'examples/asset-catalogue.tex': ('\n'.join(tex) + '\n').encode('utf-8'),
    }


def check_catalogue(root=ROOT):
    files = catalogue_files(root)
    stale = [name for name, content in files.items()
             if not (root / name).is_file() or (root / name).read_bytes() != content]
    if stale:
        raise RuntimeError('Icon catalogue is stale: ' + ', '.join(stale)
                           + '. Run python3 scripts/build-asset-catalogue.py (py -3 on Windows).')
    return len(files)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check freshness without writing files')
    parser.add_argument('--root', type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        if args.check:
            check_catalogue(root)
            print('Icon catalogue is current.')
        else:
            for name, content in catalogue_files(root).items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                write_if_changed(path, content)
            print('Icon catalogue generated from the current library.')
        return 0
    except (OSError, ValueError, RuntimeError) as error:
        print(f'Catalogue failed: {error}', file=sys.stderr)
        return 1
