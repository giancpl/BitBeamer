ROOT = Path(__file__).resolve().parents[1]
NAME = re.compile(r'[a-z][a-z0-9-]*\Z')


def check_prepared_resources(root=ROOT, entries=None):
    """Verify retained PDF parts without importing any conversion library."""
    if entries is None:
        index = root / 'templates/index.json'
        if not index.exists():
            return 0
        entries = json.loads(index.read_text(encoding='utf-8'))['templates']
    # Retained vector PDF parts need no conversion or access to their original export.
    for entry in entries:
        for relative, expected in entry.get('prepared_resources', {}).items():
            path = root / relative
            if not path.resolve().is_relative_to(root.resolve()) or not path.is_file():
                raise RuntimeError('Missing prepared Studio resource: ' + relative)
            if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
                raise RuntimeError('Changed prepared Studio resource: ' + relative)
    return sum(len(entry.get('prepared_resources', {})) for entry in entries)


def inspect_templates(root=ROOT):
    data = json.loads((root / 'templates/index.json').read_text(encoding='utf-8'))
    entries = data['templates']
    names = set()
    for entry in entries:
        name = entry['id']
        if not NAME.fullmatch(name) or name in names:
            raise RuntimeError('Invalid or repeated Studio template name: ' + name)
        names.add(name)
        if entry['source'] != f'templates/studio/{name}.tex':
            raise RuntimeError('Unexpected template path: ' + entry['source'])
        source = root / entry['source']
        if not source.is_file() or not source.read_text(encoding='utf-8').strip():
            raise RuntimeError('Missing Studio template: ' + entry['source'])
    actual = {p.stem for p in (root / 'templates/studio').glob('*.tex') if p.name != 'registry.tex'}
    if actual != names:
        raise RuntimeError('Studio metadata and source files disagree: ' + ', '.join(sorted(actual ^ names)))
    inventory = json.loads((root / 'templates/figma-inventory.json').read_text(encoding='utf-8'))
    references = {entry['id'] for entry in inventory['frames']}
    for entry in entries:
        if not set(entry['references']).issubset(references):
            raise RuntimeError('Missing Figma reference for ' + entry['id'])
    from studio_slots import validate
    validate(entries)
    from studio_review import reviewed_entries
    entries = reviewed_entries(root, entries)
    inspect_aliases(root, entries)
    from studio_models import validate as validate_models
    validate_models(root, entries)
    # Keep closing last even as new layouts are appended to the library.
    return [e for e in entries if e['id'] != 'closing'] + [e for e in entries if e['id'] == 'closing']


def inspect_aliases(root=ROOT, entries=None):
    entries = entries if entries is not None else json.loads((root / 'templates/index.json').read_text(encoding='utf-8'))['templates']
    known = {entry['id']: entry for entry in entries}
    aliases = json.loads((root / 'templates/index.json').read_text(encoding='utf-8')).get('aliases', [])
    seen = set(known)
    for alias in aliases:
        name, target = alias['id'], alias['alias_of']
        if not NAME.fullmatch(name) or name in seen or target not in known:
            raise RuntimeError('Invalid Studio compatibility name: ' + name)
        seen.add(name)
        if alias['source'] != known[target]['source']:
            raise RuntimeError('Compatibility name must share its current source: ' + name)
        fields = {field['name'] for field in known[target]['fields']}
        if set(alias.get('overrides', {})) - fields:
            raise RuntimeError('Unknown compatibility default in ' + name)
    from studio_review import load_review
    ledger = load_review(root)
    return [dict(a, fields=known[a['alias_of']]['fields'], parts=known[a['alias_of']].get('parts', []),
                 slot_parts=known[a['alias_of']].get('slot_parts', []),
                 neutral_parts=known[a['alias_of']].get('neutral_parts', []),
                 shared_sources=known[a['alias_of']].get('shared_sources', []),
                 prepared_resources=known[a['alias_of']].get('prepared_resources', {}),
                 status=ledger['templates'][a['alias_of']]['status']) for a in aliases]


def registry_document(entries, aliases=()):
    lines = ['% Generated by scripts/build-studio-catalogue.py.']
    from studio_slots import declarations
    for entry in entries:
        lines.append(r'\DeclareStudioTemplate{' + entry['id'] + '}')
        lines.extend(declarations(entry))
    declared = {entry['id'] for entry in entries}
    for alias in aliases:
        target = alias['alias_of']
        if target not in declared:
            lines.append(r'\DeclareStudioTemplate{' + target + '}')
            lines.extend(declarations(dict(alias,id=target)))
            declared.add(target)
        defaults = ','.join(key + '={' + value + '}' for key, value in alias.get('overrides', {}).items())
        lines.append(r'\DeclareStudioTemplateAlias{' + alias['id'] + '}{' + alias['alias_of'] + '}{' + defaults + '}')
    from studio_models import registry as model_registry
    model_entries=list(entries)
    metadata={e['id']:e for e in json.loads((ROOT/'templates/index.json').read_text())['templates']}
    for alias in aliases:
        if alias['alias_of'] not in {e['id'] for e in model_entries}:model_entries.append(metadata[alias['alias_of']])
    lines.extend(model_registry(ROOT, model_entries))
    return '\n'.join(lines) + '\n'


def catalogue_document(entries):
    lines = ['% Generated by scripts/review.py sync; edit templates/studio sources.', r'\documentclass[aspectratio=169]{beamer}', r'\usetheme{bitpolito-studio}',
             r'\usepackage{bitpolitostudiotemplates}', r'\usepackage[backend=biber]{biblatex}',
             r'\addbibresource{bibliography.bib}', r'\title{Studio\\Layout Library}',
             r'\author{BitPolito}', r'\institute{Editable slide templates}', r'\date{}',
             '% Catalogue labels are not added to normal user decks.',
             r'\newcommand{\studiocataloguename}{}',
             r'\AddToHook{shipout/foreground}{\begin{tikzpicture}[remember picture,overlay]',
             r'\node[anchor=south,fill=white,text=bitpolito,rounded corners=2pt,inner sep=2pt,',
             r'font=\fontsize{5}{6}\selectfont] at ([yshift=0.012\paperheight]current page.south)',
             r'{\insertframenumber\quad\texttt{\string\studiotemplate\{\studiocataloguename\}}};\end{tikzpicture}}', r'\begin{document}']
    previous_category = None
    for entry in entries:
        if entry['category'] != previous_category:
            lines.append(r'\section{' + entry['category'] + '}')
            previous_category = entry['category']
        lines += [r'\gdef\studiocataloguename{\detokenize{' + entry['id'] + '}}',
                  r'\studiotemplate{' + entry['id'] + '}']
    return '\n'.join(lines + [r'\end{document}', ''])


def review_index_document(entries):
    lines = ['% Generated by scripts/review.py sync; edit templates/studio sources.', r'\documentclass[aspectratio=169]{beamer}', r'\usetheme{bitpolito-studio}', r'\begin{document}']
    for start in range(0, len(entries), 20):
        lines += [r'\begin{frame}{Studio review index}\fontsize{6.5}{9}\selectfont\begin{columns}[T]']
        for column in (entries[start:start+10], entries[start+10:start+20]):
            lines += [r'\begin{column}{.48\textwidth}\begin{tabular}{rl}']
            lines += [str(entry['number']) + r' & \texttt{' + entry['id'] + r'} \\' for entry in column]
            lines += [r'\end{tabular}\end{column}']
        lines += [r'\end{columns}\end{frame}']
    return '\n'.join(lines + [r'\end{document}', ''])


def geometry_document(entries):
    source = catalogue_document(entries)
    first = source.index('% Catalogue labels')
    last = source.index(r'\begin{document}')
    return source[:first] + r'\studiogeometryonlytrue' + '\n' + source[last:]


