def check_gallery(root):
    from studio_preview import input_sets, load_manifest, digest
    entries = inspect_templates(root)
    manifest = load_manifest(root)
    if manifest.get('schema') != 2:
        raise RuntimeError('Gallery previews need migration. Run python3 scripts/review.py all.')
    expected = input_sets(root, entries)
    stale = [name for name, values in expected.items() if manifest.get('models', {}).get(name) != values]
    if stale:
        raise RuntimeError('Gallery previews are stale for: ' + ', '.join(stale) + '. Run python3 scripts/review.py slide <id>, or all.')
    if set(manifest.get('previews', {})) != set(expected):
        raise RuntimeError('Gallery preview entries disagree with the library')
    for name, value in manifest['previews'].items():
        png = root / 'docs/templates/previews' / (name + '.png')
        if not png.is_file() or digest(png) != value:
            raise RuntimeError('Missing or changed Studio preview: ' + name)
    return len(expected)


def prepare_catalogue(root=ROOT, check=False):
    for relative, content in generated_files(root).items():
        path = root / relative
        data = content.encode('utf-8')
        if check:
            if not path.is_file() or path.read_bytes().replace(b'\r\n', b'\n') != data:
                raise RuntimeError(f'Stale Studio catalogue file: {relative}. Run python3 scripts/build-studio-catalogue.py.')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            write_if_changed(path, data)
    if check:
        check_gallery(root)
        check_prepared_resources(root)
    return len(inspect_templates(root))


def render_previews(root, pdf):
    entries = inspect_templates(root)
    tool = shutil.which('pdftocairo')
    info = shutil.which('pdfinfo')
    if not tool or not info:
        raise RuntimeError('Preview maintenance needs Poppler (pdftocairo and pdfinfo). Ordinary builds do not.')
    details = subprocess.check_output([info, str(pdf)], text=True)
    pages = int(re.search(r'(?m)^Pages:\s+(\d+)', details).group(1))
    if pages != len(entries):
        raise RuntimeError(f'Catalogue has {pages} pages; expected {len(entries)}. Rebuild it first.')
    output = root / 'docs/templates/previews'
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='bitbeamer-template-previews-') as temporary:
        prefix = Path(temporary) / 'page'
        subprocess.run([tool, '-png', '-scale-to-x', '480', '-scale-to-y', '-1', str(pdf), str(prefix)], check=True)
        files = sorted(Path(temporary).glob('page-*.png'), key=lambda p:int(p.stem.split('-')[-1]))
        for entry, source in zip(entries, files):
            write_if_changed(output / (entry['id'] + '.png'), source.read_bytes())
    current_names = {entry['id'] for entry in entries}
    for old in output.glob('*.png'):
        if old.stem not in current_names:
            old.unlink()
    from studio_preview import input_sets, digest, save_manifest
    manifest = {'schema': 2, 'models': input_sets(root, entries),
                'previews': {e['id']: digest(output / (e['id'] + '.png')) for e in entries}}
    save_manifest(root, manifest)
    return len(entries)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check metadata and generated indices without writing files')
    parser.add_argument('--previews', type=Path, help='Refresh prepared gallery PNGs from the compiled full catalogue')
    args = parser.parse_args(argv)
    try:
        count = prepare_catalogue(check=args.check)
        if args.previews:
            if args.check:
                raise ValueError('--check cannot regenerate previews')
            render_previews(ROOT, args.previews.resolve())
        print(f'Studio template catalogue ready: {count} editable layouts.')
        return 0
    except (OSError, RuntimeError, ValueError, subprocess.CalledProcessError) as error:
        print(f'Studio catalogue failed: {error}')
        return 1
