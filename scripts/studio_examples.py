"""Keep English content examples separate from reusable neutral Studio layouts."""
import json
import re
from pathlib import Path

from studio_guides import command
from studio_models import membership
from studio_templates import catalogue_document


def previous_values(root):
    result = {}
    for item in json.loads((root / 'templates/default-content-audit.json').read_text())['fields']:
        key = (item['composition'], item['field'])
        if key in result:
            raise RuntimeError('Duplicate historical content field: ' + '/'.join(key))
        result[key] = item['previous']
    return result


def example_values(root, entry):
    """Reuse numbered slots so historical field names cannot collide with semantic adapters."""
    previous = previous_values(root)
    values = {}
    for field in entry.get('fields', []):
        key = (entry['id'], field['name'])
        if field['type'] == 'text' and key in previous:
            value = previous[key]
            if key == ('code', 'text-2'):
                # This historical code block was serialized with every escape doubled.
                # Decode one layer; keep the archived value untouched.
                value = re.sub(r'\\{2,}', lambda match: '\\' * (len(match[0]) // 2), value)
            else:
                value = value.replace(r'\\\\', r'\\')
            values[field['slot']['key']] = value
    originals = entry.get('original_parts', [])
    graphics = sorted((f for f in entry.get('fields', []) if f['type'] == 'graphic'),
                      key=lambda f: int(f['name'].rsplit('-', 1)[-1])) if originals else []
    if originals and len(originals) != len(graphics):
        raise RuntimeError('Original graphic mapping needs review: ' + entry['id'])
    for field, name in zip(graphics, originals):
        # Original collection part names have a stable prepared location. Generation
        # remains possible in metadata-only check fixtures; artwork checks validate PDFs.
        path = Path('images/studio/collection') / (name + '.pdf')
        values[field['slot']['key']] = r'\includegraphics{' + path.as_posix() + '}'
    return values


def exact_command(root, entry, content='neutral'):
    model, variant, composition = membership(root)[entry['id']]
    values = {'variant': variant['id'], 'palette': composition['native_palette']}
    if content == 'example':
        values.update(example_values(root, entry))
    elif content != 'neutral':
        raise ValueError('Unknown content mode: ' + content)
    return command(model['id'], values)


def content_document(root, entries, content='example'):
    source = catalogue_document(entries)
    # Keep the whole slide canvas visible in review decks.
    source = source[:source.index('% Catalogue labels')] + source[source.index(r'\begin{document}'):]
    for entry in entries:
        source = source.replace(r'\studiotemplate{' + entry['id'] + '}', exact_command(root, entry, content))
    return '% Generated by scripts/review.py sync. Layout sources are shared; edit a copied command.\n' + source


def reusable_entries(root, entries):
    ledger = json.loads((root / 'templates/review.json').read_text())
    ids = ledger.get('reusable_selection', [])
    known = {entry['id']: entry for entry in entries}
    if not ids or len(ids) != len(set(ids)) or set(ids) - set(known):
        raise RuntimeError('Invalid reusable_selection in templates/review.json')
    return [known[name] for name in ids]


def generated(root, entries):
    chosen = reusable_entries(root, entries)
    previous = previous_values(root)
    restored = {name for name, _ in previous}
    lines = ['# Studio ready-content examples', '',
             'Generated by `python3 scripts/review.py sync` from the current library and retained English content history.', '',
             f'This catalogue preserves {len(entries)} compositions. Historical text overrides are available for {len(restored)}; the others retain their current defaults.',
             'These are editable English reconstructions, not original Figma exports or newly verified factual claims.',
             'Historical numbers, names and links are examples; check them before presenting.', '',
             'Copy commands from [the complete source](../examples/studio-ready-content.tex), or compile only one example:', '',
             '```sh', 'python3 scripts/review.py slide three-cards --content example --open',
             '# Title, contents and closing alternatives only:', 'python3 scripts/review.py pages --content example --open', '```', '',
             'The complete PDF is optional: `python3 scripts/build.py examples/studio-ready-content.tex build/review`.',
             'Original graphic parts replaced by neutral placeholders are restored through explicit graphic slots.',
             'Layout geometry, fonts and field APIs are shared with neutral templates. Topic-specific diagrams remain examples.', '',
             '| Composition | Historical text | Editable layout |', '| --- | --- | --- |']
    for entry in entries:
        count = sum((entry['id'], f['name']) in previous for f in entry.get('fields', []) if f['type'] == 'text')
        lines.append(f"| `{entry['id']}` | {count} fields | [{entry['id']}.tex](studio/{entry['id']}.tex) |")
    neutral = ['# Studio reusable shortlist', '',
               'Generated by `python3 scripts/review.py sync`. Edit `reusable_selection` in [review.json](review.json).', '',
               'This initial shortlist focuses on title, contents and closing. It is separate from the existing showcase selection and graphical approval.',
               'Neutral content helps create a new presentation. Other compositions remain in the [ready-content catalogue](EXAMPLES.md) and full layout library.', '',
               'Compile [the compact source](../examples/studio-reusable.tex):', '',
               '```sh', 'python3 scripts/build.py examples/studio-reusable.tex build/review --open', '```', '',
               'Agenda fields are currently manual. Automatic section binding will follow the visual choice.', '',
               '| Role | Composition | Editable source |', '| --- | --- | --- |']
    for entry in chosen:
        neutral.append(f"| {entry['title']} | `{entry['id']}` | [{entry['id']}.tex](studio/{entry['id']}.tex) |")
    neutral += ['', '## Copyable commands', '']
    for entry in chosen:
        neutral += ['### ' + entry['id'], '', '```latex', exact_command(root, entry), '```', '']
    return {Path('examples/studio-ready-content.tex'): content_document(root, entries),
            Path('examples/studio-reusable.tex'): content_document(root, chosen, 'neutral'),
            Path('templates/EXAMPLES.md'): '\n'.join(lines) + '\n',
            Path('templates/REUSABLE.md'): '\n'.join(neutral).rstrip() + '\n'}
